using UnityEngine;

namespace GoodCopBadCop.FilmStudio
{
    /// <summary>
    /// Named blocking mark inside a <see cref="StudioSet"/>. Claude moves actors between marks
    /// instead of emitting raw coordinates. The mark's forward is the default facing.
    /// </summary>
    public class StudioMark : MonoBehaviour
    {
        public string markId;
        [TextArea(1, 3)] public string description;
        [Tooltip("Auto-generated by StudioSetAnalyzer (facing, open space, nearby points). Regenerated on analysis; edit 'description' instead.")]
        [TextArea(1, 4)] public string context;

        private void OnDrawGizmos()
        {
            Vector3 p = transform.position;
            Gizmos.color = new Color(1f, 0.75f, 0.1f, 0.9f);
            const int segments = 20;
            const float radius = 0.35f;
            for (int i = 0; i < segments; i++)
            {
                float a0 = i / (float)segments * Mathf.PI * 2f;
                float a1 = (i + 1) / (float)segments * Mathf.PI * 2f;
                Gizmos.DrawLine(p + new Vector3(Mathf.Cos(a0), 0f, Mathf.Sin(a0)) * radius,
                                p + new Vector3(Mathf.Cos(a1), 0f, Mathf.Sin(a1)) * radius);
            }
            Gizmos.DrawLine(p, p + transform.forward * 0.6f);
        }
    }
}
